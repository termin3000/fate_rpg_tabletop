// ── Weighted random selection ──────────────────────────────────
// Picks an entry from the table. Entries with a higher `weight` value
// are more likely to be chosen. Default weight is 1.
export function rollOnTable(table: RandomTable): string {
  if (table.entries.length === 0) return '';
  const weights = table.entries.map((e) => (e.weight ?? 1) > 0 ? (e.weight ?? 1) : 1);
  const total = weights.reduce((sum, w) => sum + w, 0);
  let r = Math.random() * total;
  for (let i = 0; i < table.entries.length; i++) {
    r -= weights[i];
    if (r < 0) return table.entries[i].text;
  }
  // Fallback (shouldn't happen due to floating-point rounding)
  return table.entries[table.entries.length - 1].text;
}

// ── Roll on custom table (simple string entries, no weights) ──
export function rollOnCustomTable(entries: string[]): string {
  if (entries.length === 0) return '';
  const idx = Math.floor(Math.random() * entries.length);
  return entries[idx];
}
